"""Retire only exact duplicate local copies; preserve every evidence byte."""
from pathlib import Path
import hashlib,json,shutil,subprocess,zipfile
b=Path('/workspace/2237-cache-duplication');out=b/'runtime-retention';records=[]
def sha(p):return hashlib.file_digest(p.open('rb'),'sha256').hexdigest()
# Immutable public download copies, not original authored files.
for name,receipt in [('checkpoint-public-download.zip','checkpoint-readable-verification.json'),('final-public-download.zip','final-readable-verification.json')]:
 p=b/name;r=json.loads((b/receipt).read_text());assert p.stat().st_size==r['archive_bytes'] and sha(p)==r['archive_sha256'];records.append(dict(kind='public_download_duplicate',path=str(p),bytes=p.stat().st_size,sha256=sha(p),retained_authority=r['archive_url'],receipt=receipt));p.unlink()
# Store canonical harness source before retiring any verified extracted copies.
for p in (b/'canonical').rglob('*.py'):
 dest=out/'canonical-harness-template'/p.relative_to(b/'canonical');dest.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(p,dest)
# A clean evidence checkout can be narrowed without deleting Git/public history.
c=Path('/workspace/cache-sharing-handoff');assert not subprocess.check_output(['git','status','--porcelain'],cwd=c,text=True).strip();head=subprocess.check_output(['git','rev-parse','HEAD'],cwd=c,text=True).strip();records.append(dict(kind='sparse_checkout_only',path=str(c),retained_commit=head,public_branch='evidence/cache-string-sharing-2237'))
subprocess.run(['git','sparse-checkout','set','--no-cone','/.task-evidence/resident-refresh-ownership-2238/**','/.task-evidence/resident-refresh-ownership-2238-readback*'],cwd=c,check=True)
# Preserve known tooling source; old worktree contains only generated bytecode
# beyond its committed immutable publication tooling.
c=Path('/workspace/dtos-publisher-2237');assert not subprocess.check_output(['git','status','--porcelain'],cwd=c,text=True).strip()
head=subprocess.check_output(['git','rev-parse','HEAD'],cwd=c,text=True).strip();assert head=='f34290147664a9f550ed37138b8559919cc153f3'
for name in ['.github/workflows/canonical-release-recovery.yml','.github/release-plans/2237.json','.github/release-plans/README.md','tools/release/__init__.py','tools/release/publish.py','tests/test_release_publisher.py']:
 dest=out/'publisher-template'/name;dest.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(c/name,dest)
records.append(dict(kind='clean_worktree_duplicate',path=str(c),retained_commit=head,retained_ref='release/2237-actions-publisher'))
subprocess.run(['git','worktree','remove',str(c)],cwd='/workspace/dtos',check=True)
# Retire old extraction folders only if every file matches a retained ZIP entry.
for folder,archive in [('/workspace/2217-evidence/canonical','/workspace/2217-evidence/canonical.zip'),('/workspace/2217-evidence/focused','/workspace/2217-evidence/focused.zip'),('/workspace/2217-evidence/superseded-cancelled','/workspace/2217-evidence/superseded-cancelled.zip'),('/workspace/2218-evidence/canonical','/workspace/2218-evidence/canonical.zip'),('/workspace/2218-evidence/focused','/workspace/2218-evidence/focused.zip'),('/workspace/2237-cache-duplication/host-canonical-readable','/workspace/2237-cache-duplication/hosted-originals/canonical-release-2g-python314.zip')]:
 target=Path(folder);archive=Path(archive);files=[p for p in target.rglob('*') if p.is_file()];matched=False
 with zipfile.ZipFile(archive) as z:
  assert z.testzip() is None
  for prefix in ['',target.name+'/','local-canonical/']:
   rows=[]
   try:
    for p in files:
     data=z.read(prefix+str(p.relative_to(target)));actual=sha(p)
     if len(data)!=p.stat().st_size or hashlib.sha256(data).hexdigest()!=actual:break
     rows.append(dict(name=str(p.relative_to(target)),bytes=len(data),sha256=actual))
    else:
     matched=True;break
   except (KeyError,PermissionError):continue
  if matched:
   records.append(dict(kind='exact_zip_extraction_duplicate',path=str(target),archive=str(archive),archive_sha256=sha(archive),prefix=prefix,files=rows,bytes=sum(x['bytes'] for x in rows)));shutil.rmtree(target)
  else:records.append(dict(kind='preserved_unmatched_folder',path=str(target),reason='Not every extracted file matched retained archive;nothing removed.'))
# Remove duplicate delivery ZIPs only when a byte-identical original remains.
for parent in ['/workspace/2217-evidence','/workspace/2218-evidence']:
 parent=Path(parent);originals={sha(p):p for p in parent.glob('*.zip')}
 for directory in ['delivery','page-files']:
  for p in (parent/directory).rglob('*'):
   if p.is_file() and p.stat().st_size>1024*1024:
    digest=sha(p);authority=originals.get(digest)
    if authority:
     records.append(dict(kind='byte_identical_delivery_duplicate',path=str(p),retained_path=str(authority),sha256=digest,bytes=p.stat().st_size));p.unlink()
(out/'validation-storage-retirement.json').write_text(json.dumps(records,indent=2)+'\n');print('Verified retirement records:',len(records),'freeGiB:',shutil.disk_usage('/workspace').free/1024**3)
